package org.example.service.chatbot;

import jakarta.persistence.EntityManager;
import org.example.dto.response.AiChatResult;
import org.example.dto.response.AiRecipeResponse;
import org.example.dto.response.AiRecipeSummaryResponse;
import org.example.entity.chatbot.AiRecipe;
import org.example.entity.chatbot.AiRecipeIngredient;
import org.example.entity.chatbot.ChatMessage;
import org.example.entity.common.User;
import org.example.mapper.AiRecipeMapper;
import org.example.repository.AiRecipeIngredientRepository;
import org.example.repository.AiRecipeRepository;
import org.springframework.http.HttpStatus;
import org.springframework.stereotype.Service;
import org.springframework.transaction.annotation.Transactional;
import org.springframework.web.server.ResponseStatusException;

import java.util.ArrayList;
import java.util.List;

@Service
public class AiRecipeStorageService {

    private final AiRecipeRepository recipes;
    private final AiRecipeIngredientRepository ingredients;
    private final EntityManager entityManager;

    public AiRecipeStorageService(
            AiRecipeRepository recipes,
            AiRecipeIngredientRepository ingredients,
            EntityManager entityManager
    ) {
        this.recipes = recipes;
        this.ingredients = ingredients;
        this.entityManager = entityManager;
    }

    @Transactional
    public List<AiRecipeResponse> saveGeneratedRecipes(
            User user,
            ChatMessage assistantMessage,
            List<AiChatResult.GeneratedRecipe> generatedRecipes
    ) {
        boolean belongsToUser = assistantMessage.getSession()
                .getUser()
                .getId()
                .equals(user.getId());

        if (!belongsToUser
                || !"ASSISTANT".equals(assistantMessage.getSender())) {
            throw new ResponseStatusException(
                    HttpStatus.FORBIDDEN,
                    "You cannot save recipes to this chat session"
            );
        }

        List<AiRecipeResponse> responses = new ArrayList<>();

        for (AiChatResult.GeneratedRecipe generated : generatedRecipes) {
            AiRecipe recipe = new AiRecipe(
                    user,
                    assistantMessage,
                    generated.name().trim(),
                    generated.description(),
                    generated.prepTime(),
                    generated.servings(),
                    generated.difficulty(),
                    java.util.stream.IntStream.range(0, generated.steps().size())
                            .mapToObj(i -> (i + 1) + ". " + generated.steps().get(i).trim())
                            .collect(java.util.stream.Collectors.joining("\n"))
            );

            recipe.setCaloriesKcal(generated.caloriesKcal());
            recipe.setCookingTip(generated.cookingTip());
            recipe.setDishType(generated.dishType());
            recipe.setRegion(generated.region());
            recipe.setCountry(
                    generated.country() == null || generated.country().isBlank()
                            ? null
                            : generated.country().trim()
            );

            recipes.saveAndFlush(recipe);

            // Read the timestamp generated by the database.
            entityManager.refresh(recipe);

            List<AiRecipeIngredient> recipeIngredients = generated
                    .ingredients()
                    .stream()
                    .map(ingredient -> new AiRecipeIngredient(
                            recipe,
                            ingredient.ingredientName().trim(),
                            ingredient.quantity().trim()
                    ))
                    .toList();

            List<AiRecipeIngredient> savedIngredients = ingredients
                    .saveAllAndFlush(recipeIngredients);

            responses.add(
                    AiRecipeMapper.toResponse(
                            recipe,
                            savedIngredients
                    )
            );
        }

        return responses;
    }

    @Transactional(readOnly = true)
    public List<AiRecipeSummaryResponse> getMyRecipes(Integer userId) {
        return recipes.findByUserIdOrderByCreatedAtDescIdDesc(userId)
                .stream()
                .map(AiRecipeMapper::toSummaryResponse)
                .toList();
    }

    @Transactional(readOnly = true)
    public AiRecipeResponse getMyRecipe(
            Integer userId,
            Integer recipeId
    ) {
        AiRecipe recipe = findOwnedRecipe(userId, recipeId);

        List<AiRecipeIngredient> recipeIngredients = ingredients
                .findByRecipeIdOrderByIdAsc(recipe.getId());

        return AiRecipeMapper.toResponse(
                recipe,
                recipeIngredients
        );
    }

    @Transactional
    public void deleteMyRecipe(
            Integer userId,
            Integer recipeId
    ) {
        AiRecipe recipe = findOwnedRecipe(userId, recipeId);

        recipes.delete(recipe);
        recipes.flush();
    }

    private AiRecipe findOwnedRecipe(
            Integer userId,
            Integer recipeId
    ) {
        return recipes.findByIdAndUserId(recipeId, userId)
                .orElseThrow(() -> new ResponseStatusException(
                        HttpStatus.NOT_FOUND,
                        "AI recipe not found"
                ));
    }
}